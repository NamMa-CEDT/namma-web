export function agencyName(agency: string | null): string {
  switch (agency) {
    case "RID":
      return "กรมชลประทาน";
    case "HII":
      return "สถาบันสารสนเทศทรัพยากรน้ำ (สสน.)";
    case "EGAT":
      return "การไฟฟ้าฝ่ายผลิตแห่งประเทศไทย (กฟผ.)";
    case "FOP":
      return "มูลนิธิอาสาเพื่อนพึ่ง (ภาฯ) ยามยาก สภากาชาดไทย";
    case null:
    case undefined:
      return "ไม่ระบุหน่วยงาน";
    default:
      return agency;
  }
}
